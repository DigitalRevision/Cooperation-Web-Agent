def capability(code: str, name: str | None = None) -> str | None:
    best = max((p for p in CAPS if code == p or code.startswith(p + ".") or (len(p) == 4 and code.startswith(p))), key=len, default=None)
    if best:
        return CAPS[best]
    # прочие коды обрабатывающих производств: название вида деятельности как есть
    if name and code[:2].isdigit() and 10 <= int(code[:2]) <= 33:
        return name[:120]
    return None


def declared(okved_all: list[tuple[str, str]]) -> list[dict]:
    out: dict[str, list[str]] = {}
    for code, name in okved_all:
        cap = capability(code, name)
        if cap:
            out.setdefault(cap, []).append(code)
    return [{"name": n, "okved": codes} for n, codes in out.items()]
